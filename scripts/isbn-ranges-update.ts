import { writeFile } from "node:fs/promises";

const RANGE_MESSAGE_URL = "https://www.isbn-international.org/export_rangemessage.xml";
const OUTPUT_PATH = new URL("../src/text/isbnRanges.ts", import.meta.url);

const BLOCK_PATTERN =
  /<(?:EAN\.UCC|Group)>\s*<Prefix>([\d-]+)<\/Prefix>[\s\S]*?<Rules>([\s\S]*?)<\/Rules>/g;
const RULE_PATTERN = /<Range>(\d+)-(\d+)<\/Range>\s*<Length>(\d+)<\/Length>/g;
const MESSAGE_DATE_PATTERN = /<MessageDate>([^<]+)<\/MessageDate>/;

const fetchRangeMessage = async (): Promise<string> => {
  const response = await fetch(RANGE_MESSAGE_URL);

  if (!response.ok) {
    throw new Error(`Failed to fetch ${RANGE_MESSAGE_URL}: ${response.status}`);
  }

  return response.text();
};

const renderRules = (rulesXml: string): string[] => {
  const lines: string[] = [];

  for (const [, start, end, length] of rulesXml.matchAll(RULE_PATTERN)) {
    if (length === "0") continue;
    lines.push(`    [${Number(start)}, ${Number(end)}, ${length}],`);
  }

  return lines;
};

const renderModule = (xml: string): string => {
  const messageDate = xml.match(MESSAGE_DATE_PATTERN)?.[1];

  if (!messageDate) {
    throw new Error("Range message has no <MessageDate>");
  }

  const lines = [
    "// Generated by scripts/isbn-ranges-update.ts. Do not edit by hand.",
    `// Source: International ISBN Agency range message, ${messageDate}.`,
    "",
    "// [start, end, length]: when the 7 digits after a prefix fall in",
    "// start..end, the next part of the ISBN is `length` digits long.",
    "export type IsbnRangeRule = readonly [start: number, end: number, length: number];",
    "",
    "export const ISBN_RANGE_RULES: Readonly<Record<string, readonly IsbnRangeRule[]>> = {",
  ];
  let blockCount = 0;

  for (const [, prefix, rulesXml] of xml.matchAll(BLOCK_PATTERN)) {
    const ruleLines = renderRules(rulesXml);

    if (ruleLines.length === 0) {
      continue;
    }

    lines.push(`  "${prefix}": [`, ...ruleLines, "  ],");
    blockCount += 1;
  }

  if (blockCount === 0) {
    throw new Error("Range message contained no prefixes with rules");
  }

  lines.push("};", "");

  return lines.join("\n");
};

const xml = await fetchRangeMessage();
await writeFile(OUTPUT_PATH, renderModule(xml));
process.stdout.write(`Wrote ${OUTPUT_PATH.pathname}\n`);
